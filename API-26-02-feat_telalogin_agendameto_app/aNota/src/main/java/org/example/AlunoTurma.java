package org.example;

public class AlunoTurma {

    private final String ra;
    private final String nome;

    public AlunoTurma(String ra, String nome) {
        this.ra = ra;
        this.nome = nome;
    }

    public String getRa() {
        return ra;
    }

    public String getNome() {
        return nome;
    }
}
